// Generate amplify/functions/graph-shared/ontology.generated.ts from
// packages/ontology, the source of truth (ADR-0007). Amplify's backend build
// installs backend/ only, so the Lambdas cannot read the workspace package at
// build time; they carry this generated copy. graph-shared/validate.test.ts
// fails when it drifts.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const src = path.resolve(here, "../../packages/ontology");
// Each export is its files joined in this order (Turtle allows a prefix to be
// declared again). The perma modules are what a habitat's A-Box is checked
// against (docs/adr/0016); app/pt are the template's.
export const SOURCES = {
  TBOX: ["tbox/app.ttl", "tbox/perma-vegetation.ttl", "tbox/perma-food.ttl", "tbox/perma-habitat.ttl"],
  CONCEPTS: ["tbox/pt-concepts.ttl", "tbox/perma-vegetation-concepts.ttl", "tbox/perma-food-concepts.ttl", "tbox/perma-habitat-concepts.ttl"],
  SHAPES: ["shapes/pt-shapes.ttl", "shapes/perma-vegetation-shapes.ttl", "shapes/perma-food-shapes.ttl", "shapes/perma-habitat-shapes.ttl"],
};
export const join = (read) => (files) => files.map(read).join("\n");
const joined = join((rel) => fs.readFileSync(path.join(src, rel), "utf8"));
let out = "// GENERATED by backend/scripts/sync-ontology.mjs from packages/ontology. Do not edit.\n";
out += `export const SOURCES = ${JSON.stringify(SOURCES)};\n`;
for (const [name, files] of Object.entries(SOURCES)) {
  out += `export const ${name} = ${JSON.stringify(joined(files))};\n`;
}
const dest = path.resolve(here, "../amplify/functions/graph-shared/ontology.generated.ts");
if (import.meta.url === `file://${process.argv[1]}`) {
  fs.writeFileSync(dest, out);
  console.log(`  wrote ${path.relative(process.cwd(), dest)}`);
}
